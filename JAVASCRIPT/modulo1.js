const quizQuestion =
    document.getElementById(
        "quizQuestion"
    );


const quizOptions =
    document.getElementById(
        "quizOptions"
    );


const quizFeedback =
    document.getElementById(
        "quizFeedback"
    );


const quizNext =
    document.getElementById(
        "quizNext"
    );


const quizCounter =
    document.getElementById(
        "quizCounter"
    );


let currentQuestion = 0;


function loadQuestion() {

    if (!quizQuestion) {
        return;
    }


    const questions =
        quizData[currentLanguage];


    const question =
        questions[currentQuestion];


    quizCounter.textContent =
        currentLanguage === "es"
        ?
        `Pregunta ${currentQuestion + 1} de ${questions.length}`
        :
        `Question ${currentQuestion + 1} of ${questions.length}`;


    quizQuestion.textContent =
        question.question;


    quizOptions.innerHTML = "";

    quizFeedback.textContent = "";

    quizNext.disabled = true;


    question.options.forEach(
        function(option, index) {

            const button =
                document.createElement(
                    "button"
                );


            button.type = "button";

            button.className =
                "quiz-option";

            button.textContent =
                option;


            button.addEventListener(
                "click",
                function() {

                    checkAnswer(
                        index,
                        button
                    );

                }
            );


            quizOptions.appendChild(
                button
            );

        }
    );


    quizNext.textContent =
        currentQuestion ===
        questions.length - 1
        ?
        (
            currentLanguage === "es"
            ?
            "Finalizar"
            :
            "Finish"
        )
        :
        (
            currentLanguage === "es"
            ?
            "Siguiente pregunta →"
            :
            "Next question →"
        );

}


function checkAnswer(
    selectedIndex,
    selectedButton
) {

    const question =
        quizData[currentLanguage]
        [currentQuestion];


    const buttons =
        quizOptions.querySelectorAll(
            ".quiz-option"
        );


    buttons.forEach(
        function(button) {

            button.disabled = true;

        }
    );


    if (
        selectedIndex ===
        question.answer
    ) {

        selectedButton.classList.add(
            "correct"
        );


        quizFeedback.textContent =
            (
                currentLanguage === "es"
                ?
                "✓ Correcto. "
                :
                "✓ Correct. "
            )
            +
            question.feedback;

    }

    else {

        selectedButton.classList.add(
            "incorrect"
        );


        buttons[
            question.answer
        ].classList.add(
            "correct"
        );


        quizFeedback.textContent =
            (
                currentLanguage === "es"
                ?
                "✗ Revisa la respuesta. "
                :
                "✗ Review the answer. "
            )
            +
            question.feedback;

    }


    quizNext.disabled = false;

}


if (quizNext) {

    quizNext.addEventListener(
        "click",
        function() {

            const questions =
                quizData[
                    currentLanguage
                ];


            if (
                currentQuestion <
                questions.length - 1
            ) {

                currentQuestion++;

                loadQuestion();

            }

            else {

                quizQuestion.textContent =
                    currentLanguage === "es"
                    ?
                    "¡Actividad completada!"
                    :
                    "Activity completed!";


                quizOptions.innerHTML = "";


                quizFeedback.textContent =
                    currentLanguage === "es"
                    ?
                    "Terminaste la actividad de identificación de amenazas digitales."
                    :
                    "You completed the digital threat identification activity.";


                quizCounter.textContent =
                    "✓";


                quizNext.style.display =
                    "none";

            }

        }
    );

}


function resetQuiz() {

    if (!quizQuestion) {
        return;
    }


    currentQuestion = 0;

    quizNext.style.display =
        "inline-block";

    loadQuestion();

}


